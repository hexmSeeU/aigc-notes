const read=path=>{
 assert.ok(fs.existsSync(path),`Expected ${path}`);
 const source=fs.readFileSync(path,'utf8'),end=source.indexOf('\n}\n')+2;
 return {meta:JSON.parse(source.slice(0,end)),body:historicalLinks(source.slice(end).trim())};
};
